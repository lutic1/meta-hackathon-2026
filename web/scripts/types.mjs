// Compiles web/types/schema.json (the GET /schema body) into web/types/index.ts (AD-2, AD-3).
// Run through `npm run types`, which first writes schema.json with scripts/schema.py.
//
// The client gets every model and union the browser sends or receives, never a
// server-only one: SERVER_ONLY and every type reachable only through them are
// dropped, and a union member that is server-only leaves the union. Keys stay
// exactly as in the JSON (snake_case). The header records the sha256 of
// schema.json and of this script, which tests/web/test_types.py checks.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { compile } from 'json-schema-to-typescript'

const SCHEMA_JSON = new URL('../types/schema.json', import.meta.url)
const INDEX_TS = new URL('../types/index.ts', import.meta.url)
const REF = '#/$defs/'

// The full Room and the model-response, prompt and edit shapes stay on the server (AD-3).
const SERVER_ONLY = new Set([
  'Room',
  'RoomDraft',
  'ArchitectResponse',
  'DryRunAnswers',
  'RoomView',
  'TricksterEdit',
  'TricksterCardEvent',
])

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const refName = (node) => node.$ref.slice(REF.length)
const isServerOnlyRef = (node) => typeof node?.$ref === 'string' && SERVER_ONLY.has(refName(node))

// One schema node made ready for the compiler: no property titles (they would become
// type aliases), tuples as `items` arrays, string-keyed maps as index signatures, and
// no server-only member in a tagged union (`oneOf`). Any other reference to a
// server-only type fails the run below.
function clean(node, keepTitle = false) {
  if (Array.isArray(node)) return node.map((item) => clean(item))
  if (node === null || typeof node !== 'object') return node
  const out = {}
  for (const [key, value] of Object.entries(node)) {
    if (key === 'title' && !keepTitle) continue
    if (key === 'properties') {
      out.properties = Object.fromEntries(Object.entries(value).map(([name, prop]) => [name, clean(prop)]))
    } else if (key === 'prefixItems') {
      out.items = clean(value)
    } else if (key === 'patternProperties') {
      out.additionalProperties = clean(Object.values(value)[0])
    } else if (key === 'oneOf') {
      out.oneOf = clean(value.filter((member) => !isServerOnlyRef(member)))
    } else {
      out[key] = clean(value)
    }
  }
  return out
}

function refsIn(node, found = new Set()) {
  if (Array.isArray(node)) node.forEach((item) => refsIn(item, found))
  else if (node !== null && typeof node === 'object') {
    if (typeof node.$ref === 'string') found.add(refName(node))
    Object.values(node).forEach((value) => refsIn(value, found))
  }
  return found
}

const source = readFileSync(SCHEMA_JSON)
const schema = JSON.parse(source.toString('utf8'))
const defs = Object.fromEntries(Object.entries(schema.$defs).map(([name, def]) => [name, clean(def, true)]))

// Roots are the served models and unions no other type refers to; the rest come in by reference.
const referenced = new Set(Object.values(defs).flatMap((def) => [...refsIn(def)]))
const roots = Object.keys(defs).filter((name) => !referenced.has(name) && !SERVER_ONLY.has(name))
const kept = new Set()
const queue = [...roots]
while (queue.length > 0) {
  const name = queue.pop()
  if (kept.has(name)) continue
  if (SERVER_ONLY.has(name)) throw new Error(`a client type refers to the server-only ${name}`)
  kept.add(name)
  queue.push(...refsIn(defs[name]))
}

const root = {
  $defs: Object.fromEntries([...kept].sort().map((name) => [name, defs[name]])),
  anyOf: roots.sort().map((name) => ({ $ref: `${REF}${name}` })),
}
const compiled = await compile(root, 'ClientRoot', { bannerComment: '', additionalProperties: false })
// The compiler declares the root union first; it names no shape the API sends, so it is dropped.
const body = compiled.slice(compiled.indexOf(';\n') + 2).trimStart()
if (!compiled.startsWith('export type ClientRoot =') || body.includes('ClientRoot')) {
  throw new Error('unexpected compiler output: the root union is not the first declaration')
}

const generator = readFileSync(new URL(import.meta.url))
const header = [
  '// Generated by web/scripts/types.mjs from GET /schema (web/types/schema.json). Do not edit:',
  '// run `npm run types` in web/ after a schema change (tests/web/test_types.py checks these hashes).',
  `// schema.json sha256 ${sha256(source)}`,
  `// types.mjs sha256 ${sha256(generator)}`,
]
writeFileSync(INDEX_TS, `${header.join('\n')}\n\n${body}`)
console.log(`wrote web/types/index.ts: ${kept.size} types from ${roots.length} roots`)
