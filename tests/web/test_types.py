"""Story 1.15: `web/types` generated from `GET /schema`, committed, `PlayView` and never `Room`, with an offline staleness test (AR-5, AR-23, AD-2, AD-3)."""

import hashlib
import json
import re
import subprocess
from pathlib import Path

import pytest
from fastapi.testclient import TestClient
from pydantic import create_model

import src.api.app as app_module
from src.domain.schema import PlayView
from tests.api.test_app import make_app

REPO = Path(__file__).resolve().parents[2]
WEB = REPO / "web"
SCHEMA_JSON = WEB / "types/schema.json"
INDEX_TS = WEB / "types/index.ts"
GENERATOR = WEB / "scripts/types.mjs"
SERVER_ONLY = ("Room", "RoomDraft", "ArchitectResponse", "DryRunAnswers", "RoomView", "TricksterEdit", "TricksterCardEvent")
UNIONS = {
    "Event": ["ClickEvent", "LockInputEvent", "HintRequestEvent", "IdleTickEvent", "OpeningLineEvent", "RungChangeEvent"],
    "PostedEvent": ["ClickBody", "LockInputBody", "HintRequestBody"],
    "LockInput": ["CodeInput", "UseOnInput", "OrderStartInput", "OrderStopInput"],
}


def stale_types(served: dict, committed: dict) -> list[str]:
    """The `$defs` names whose schema differs between what `GET /schema` serves and `web/types/schema.json`."""
    names = set(served.get("$defs", {})) | set(committed.get("$defs", {}))
    stale = sorted(n for n in names if served.get("$defs", {}).get(n) != committed.get("$defs", {}).get(n))
    if {k: v for k, v in served.items() if k != "$defs"} != {k: v for k, v in committed.items() if k != "$defs"}:
        stale.append("(document root)")
    return stale


def _served(tmp_path: Path) -> dict:
    response = TestClient(make_app(tmp_path)).get("/api/schema")
    assert response.status_code == 200
    return response.json()


def _committed() -> dict:
    return json.loads(SCHEMA_JSON.read_text(encoding="utf-8"))


def _index() -> str:
    return INDEX_TS.read_text(encoding="utf-8")


def _declared() -> set[str]:
    return set(re.findall(r"^export (?:interface|type) (\w+)", _index(), flags=re.M))


def _interfaces() -> dict[str, str]:
    return dict(re.findall(r"^export interface (\w+) \{\n(.*?)^\}", _index(), flags=re.M | re.S))


def _keys(body: str) -> list[str]:
    """The top-level property names of one interface body (two-space indent)."""
    return re.findall(r"^  (\w+)\??:", body, flags=re.M)


def _ignored(path: str) -> bool:
    return subprocess.run(["git", "check-ignore", "-q", "--no-index", path], cwd=REPO, check=False).returncode == 0


# --- The npm script writes web/types ----------------------------------------


def test_npm_script_regenerates_web_types_from_get_schema():
    scripts = json.loads((WEB / "package.json").read_text())["scripts"]
    assert scripts["types"] == "uv run --directory .. scripts/schema.py && node scripts/types.mjs"
    assert "from 'json-schema-to-typescript'" in GENERATOR.read_text()
    assert "api_schema()" in (REPO / "scripts/schema.py").read_text()


@pytest.mark.parametrize("path", ["web/types/index.ts", "web/types/schema.json", "web/scripts/types.mjs"])
def test_generated_types_are_committed_not_ignored(path):
    assert (REPO / path).is_file() and not _ignored(path)


def test_web_types_are_type_checked():
    text = re.sub(r"/\*.*?\*/", "", (WEB / "tsconfig.json").read_text(), flags=re.S)
    assert "types" in json.loads(text)["include"]


# --- Staleness ----------------------------------------------------------------


def test_web_types_match_what_get_schema_serves(tmp_path: Path):
    served = _served(tmp_path)
    stale = stale_types(served, _committed())
    assert not stale, f"web/types is stale for {', '.join(stale)}: run `npm run types` in web/"
    assert SCHEMA_JSON.read_text(encoding="utf-8") == json.dumps(served, indent=2, ensure_ascii=False) + "\n"


def test_index_ts_was_generated_from_the_committed_schema_by_the_committed_script():
    header = _index().split("\n\n", 1)[0]
    assert header.startswith("// Generated by web/scripts/types.mjs from GET /schema")
    assert f"// schema.json sha256 {hashlib.sha256(SCHEMA_JSON.read_bytes()).hexdigest()}" in header, (
        "web/types/index.ts is stale against web/types/schema.json: run `npm run types` in web/"
    )
    assert f"// types.mjs sha256 {hashlib.sha256(GENERATOR.read_bytes()).hexdigest()}" in header, (
        "web/scripts/types.mjs changed since web/types/index.ts was generated: run `npm run types` in web/"
    )


def test_a_model_change_without_regeneration_names_the_stale_type(monkeypatch: pytest.MonkeyPatch):
    generated = app_module.api_schema()  # what the npm script last wrote, when the staleness test above passes
    changed = create_model("PlayView", __base__=PlayView, subtitle=(str, ...))
    models = tuple(changed if model is PlayView else model for model in app_module.API_MODELS)
    monkeypatch.setattr(app_module, "API_MODELS", models)
    assert stale_types(app_module.api_schema(), generated) == ["PlayView"]


def test_stale_types_names_added_removed_and_changed_types():
    committed = _committed()
    served = json.loads(json.dumps(committed))
    served["$defs"]["NewModel"] = {"type": "object"}
    del served["$defs"]["Meta"]
    served["$defs"]["RoomSummary"]["required"].append("extra")
    assert stale_types(served, committed) == ["Meta", "NewModel", "RoomSummary"]
    assert stale_types(committed, committed) == []


# --- PlayView, never Room -----------------------------------------------------


def test_play_view_is_generated_and_server_only_types_are_not():
    declared = _declared()
    assert {"PlayView", "PlayPuzzle", "SessionState", "TricksterCard", "BuildView", "Meta"} <= declared
    assert not set(SERVER_ONLY) & declared
    assert not {"Puzzle", "PuzzleDraft", "Decoy", "Provenance", "Photo", "Interactable"} & declared
    assert not [name for name in declared if "Solution" in name or "Payload" in name]


def test_no_generated_type_declares_a_solution_field():
    assert re.search(r"^\s*\"?solution\"?\??:", _index(), flags=re.M) is None
    assert all("solution" not in _keys(body) for body in _interfaces().values())


# --- Discriminated unions and snake_case keys ---------------------------------


def _literal_type(interface: str) -> str:
    match = re.search(r'^  type: "(\w+)";$', _interfaces()[interface], flags=re.M)
    assert match, f"{interface} has no Literal `type`"
    return match.group(1)


@pytest.mark.parametrize("union", UNIONS)
def test_unions_are_discriminated_on_their_literal_type(union):
    members = UNIONS[union]
    assert f"export type {union} = {' | '.join(members)};" in _index()
    literals = [_literal_type(member) for member in members]
    assert len(set(literals)) == len(literals)
    mapping = _committed()["$defs"][union]["discriminator"]["mapping"]
    assert {literal: f"#/$defs/{member}" for literal, member in zip(literals, members)} == {
        k: v for k, v in mapping.items() if v.removeprefix("#/$defs/") not in SERVER_ONLY
    }


def test_lock_input_fields_carry_the_lock_input_union():
    members = " | ".join(UNIONS["LockInput"])
    for interface in ("LockInputBody", "LockInputEvent"):
        assert f"  input: {members};" in _interfaces()[interface]


def test_every_key_is_snake_case_exactly_as_in_the_json():
    defs = _committed()["$defs"]
    interfaces = _interfaces()
    assert interfaces
    for name, body in interfaces.items():
        keys = _keys(body)
        assert all(re.fullmatch(r"[a-z][a-z0-9]*(?:_[a-z0-9]+)*", key) for key in keys), name
        assert keys == list(defs[name]["properties"]), name
